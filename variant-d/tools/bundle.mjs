// Zero-dependency browser bundle: tsc emits one AMD file (tsconfig.browser.json); this wraps it with a ~20-line
// AMD loader into (1) a classic script exposing `globalThis.EveDogma` and (2) an ES module with named exports.
import { readFileSync, writeFileSync } from 'node:fs';
const amd = readFileSync('dist-web/eve-dogma-ts.amd.js', 'utf8');
const body = `
  var defs = {}, cache = {};
  function define(name, deps, factory) { defs[name] = [deps, factory]; }
  function req(name) {
    if (cache[name]) return cache[name].exports;
    var d = defs[name];
    if (!d) throw new Error('eve-dogma-ts bundle: missing module ' + name);
    var mod = cache[name] = { exports: {} };
    var args = d[0].map(function (x) { return x === 'require' ? req : x === 'exports' ? mod.exports : req(x); });
    var r = d[1].apply(null, args);
    if (r !== undefined) mod.exports = r;
    return mod.exports;
  }
${amd}
  return req('browser');`;
const iife = `/* eve-dogma-ts (variant-d) browser bundle — generated by tools/bundle.mjs */\n(function (g) { g.EveDogma = (function () {${body}\n})(); })(typeof globalThis !== 'undefined' ? globalThis : this);\n`;
writeFileSync('dist-web/eve-dogma-ts.js', iife);
const lib = `/* eve-dogma-ts (variant-d) ES module bundle — generated by tools/bundle.mjs */\nconst EveDogma = (function () {${body}\n}).call(undefined);\n`;
const names = ['calc', 'calcJson', 'search', 'typeInfo', 'meta', 'rpc', 'eftExport', 'parseEft', 'exportEft', 'Dataset', 'ENGINE', 'loadDatasetUrl', 'inferSlot'];
writeFileSync('dist-web/eve-dogma-ts.mjs', lib + `export const { ${names.join(', ')} } = EveDogma;\nexport default EveDogma;\n`);
console.log('dist-web/eve-dogma-ts.js', iife.length, 'bytes; dist-web/eve-dogma-ts.mjs');

// Node CLI as one CommonJS file (no ESM resolution/translation at startup): node:* deps map to require()
import { existsSync } from 'node:fs';
if (existsSync('dist-cli/eve-dogma-ts.amd.js')) {
  const cli = readFileSync('dist-cli/eve-dogma-ts.amd.js', 'utf8').replace(/^#![^\n]*\n/gm, '');
  const loader = `'use strict';
var defs = {}, cache = {};
function define(name, deps, factory) { defs[name] = [deps, factory]; }
function req(name) {
  if (name.startsWith('node:')) return require(name);
  if (cache[name]) return cache[name].exports;
  var d = defs[name];
  if (!d) throw new Error('eve-dogma-ts bundle: missing module ' + name);
  var mod = cache[name] = { exports: {} };
  var args = d[0].map(function (x) { return x === 'require' ? req : x === 'exports' ? mod.exports : req(x); });
  var r = d[1].apply(null, args);
  if (r !== undefined) mod.exports = r;
  return mod.exports;
}
`;
  writeFileSync('dist-cli/eve-dogma-ts.cjs', `#!/usr/bin/env node\n/* eve-dogma-ts (variant-d) CLI bundle — generated by tools/bundle.mjs */\n${loader}${cli}\nreq('cli');\n`);
  console.log('dist-cli/eve-dogma-ts.cjs');
}
