// Zero-dependency browser bundle: tsc emits one AMD file (tsconfig.browser.json); this wraps it with a ~20-line
// AMD loader into (1) a classic script exposing `globalThis.EveDogma` and (2) an ES module with named exports.
import { readFileSync, writeFileSync } from 'node:fs';
const amd = readFileSync('dist-web/eve-dogma-ts.amd.js', 'utf8');
const body = `
  var defs = {}, cache = {};
  function define(name, deps, factory) { defs[name] = [deps, factory]; }
  function req(name) {
    if (cache[name]) return cache[name].exports;
    var d = defs[name];
    if (!d) throw new Error('eve-dogma-ts bundle: missing module ' + name);
    var mod = cache[name] = { exports: {} };
    var args = d[0].map(function (x) { return x === 'require' ? req : x === 'exports' ? mod.exports : req(x); });
    var r = d[1].apply(null, args);
    if (r !== undefined) mod.exports = r;
    return mod.exports;
  }
${amd}
  return req('browser');`;
const iife = `/* eve-dogma-ts (variant-d) browser bundle — generated by tools/bundle.mjs */\n(function (g) { g.EveDogma = (function () {${body}\n})(); })(typeof globalThis !== 'undefined' ? globalThis : this);\n`;
writeFileSync('dist-web/eve-dogma-ts.js', iife);
const lib = `/* eve-dogma-ts (variant-d) ES module bundle — generated by tools/bundle.mjs */\nconst EveDogma = (function () {${body}\n}).call(undefined);\n`;
const names = ['calc', 'calcJson', 'search', 'typeInfo', 'meta', 'rpc', 'eftExport', 'parseEft', 'exportEft', 'Dataset', 'ENGINE', 'loadDatasetUrl', 'inferSlot'];
writeFileSync('dist-web/eve-dogma-ts.mjs', lib + `export const { ${names.join(', ')} } = EveDogma;\nexport default EveDogma;\n`);
console.log('dist-web/eve-dogma-ts.js', iife.length, 'bytes; dist-web/eve-dogma-ts.mjs');

// Node CLI as one CommonJS file (no ESM resolution/translation at startup): node:* deps map to require()
import { existsSync } from 'node:fs';
if (existsSync('dist-cli/eve-dogma-ts.amd.js')) {
  const cli = readFileSync('dist-cli/eve-dogma-ts.amd.js', 'utf8').replace(/^#![^\n]*\n/gm, '');
  const loader = `'use strict';
var defs = {}, cache = {};
function define(name, deps, factory) { defs[name] = [deps, factory]; }
function req(name) {
  if (name.startsWith('node:')) return require(name);
  if (cache[name]) return cache[name].exports;
  var d = defs[name];
  if (!d) throw new Error('eve-dogma-ts bundle: missing module ' + name);
  var mod = cache[name] = { exports: {} };
  var args = d[0].map(function (x) { return x === 'require' ? req : x === 'exports' ? mod.exports : req(x); });
  var r = d[1].apply(null, args);
  if (r !== undefined) mod.exports = r;
  return mod.exports;
}
`;
  // engine: one function expression (loader + CLI); launcher: compiles it with V8's code cache when one was made
  // by `cache` (bytecode of the functions a calc runs, so a cold calc skips most lazy compilation)
  writeFileSync('dist-cli/eve-dogma-ts.engine.js', `(function (require) {\n'use strict';\n${loader.replace("'use strict';\n", '')}${cli}\nreq('cli');\n})`);
  writeFileSync('dist-cli/eve-dogma-ts.cjs', `#!/usr/bin/env node
/* eve-dogma-ts (variant-d) CLI launcher — generated by tools/bundle.mjs. Runs eve-dogma-ts.engine.js, with V8 code
   cache from .cache/ when present (written only by the \`cache\` command; stale/foreign caches are rejected by V8). */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const file = path.join(__dirname, 'eve-dogma-ts.engine.js');
const src = fs.readFileSync(file, 'utf8');
const st = fs.statSync(file);
const ccDir = process.env.EVE_DOGMA_TS_CACHE_DIR || path.join(__dirname, '..', '.cache');
const ccFile = path.join(ccDir, 'engine-' + st.size + '-' + Math.trunc(st.mtimeMs) + '-' + process.version + '.v8cc');
let cachedData;
try { cachedData = fs.readFileSync(ccFile); } catch (e) { /* no code cache */ }
const script = new vm.Script(src, { filename: file, cachedData });
globalThis.__eveDogmaCodeCache = () => {
  try {
    fs.mkdirSync(ccDir, { recursive: true });
    const tmp = ccFile + '.' + process.pid + '.tmp';
    fs.writeFileSync(tmp, script.createCachedData());
    fs.renameSync(tmp, ccFile);
    return ccFile;
  } catch (e) { return null; }
};
script.runInThisContext()(require);
`);
  // startup-snapshot builder entry (`snapshot` command): node --snapshot-blob B --build-snapshot <this> DATASET
  writeFileSync('dist-cli/eve-dogma-ts.snapshot.cjs', `/* eve-dogma-ts (variant-d) startup-snapshot entry — generated by tools/bundle.mjs */
'use strict';
const fs = require('fs'), path = require('path'), v8 = require('v8');
globalThis.__eveDogmaSnapshot = true;
(0, eval)(fs.readFileSync(path.join(__dirname, 'eve-dogma-ts.engine.js'), 'utf8'))(require);
const cli = globalThis.__eveDogmaCli;
delete globalThis.__eveDogmaSnapshot;
const pkg = path.resolve(__dirname, '..');
cli.preload(process.argv[2], pkg);
v8.startupSnapshot.setDeserializeMainFunction(() => cli.run(process.argv.slice(1), pkg));
`);
  console.log('dist-cli/eve-dogma-ts.cjs');
}
